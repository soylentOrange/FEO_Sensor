import schemdraw, schemdraw.elements as elm
schemdraw.config(fontsize=11)
d = schemdraw.Drawing(show=False)
d.config(unit=2.4)

# ---- Vref divider ----
vdd1 = d.add(elm.Vdd().at((0, 4)).label('VDD (XIAO D1)'))
r3 = d.add(elm.Resistor().down().at((0,4)).label('R3\n330k', loc='bottom'))
d.add(elm.Dot())
vref = r3.end
r4 = d.add(elm.Resistor().down().label('R4\n10k', loc='bottom'))
d.add(elm.Ground())
d.add(elm.Line().right().at(vref).length(1.5))
d.add(elm.Label().label('VREF ≈ 0,1 V', loc='top'))
# ---- U1B FSR stage ----
opB = d.add(elm.Opamp(leads=True).flip().right().anchor('in2').at((vref[0]+3.0, vref[1])).label('U1B\nMCP602', loc='center', ofst=(0.2,0)))
d.add(elm.Line().at(vref).to(opB.in2))
d.add(elm.Label().at(opB.in2).label('5', loc='top', ofst=(-0.3,0)))
d.add(elm.Label().at(opB.in1).label('6', loc='bottom', ofst=(-0.3,0)))
d.add(elm.Label().at(opB.out).label('7', loc='top', ofst=(0.2,0)))
n6 = d.add(elm.Dot().at(opB.in1))
d.add(elm.Line().down().at(opB.in1).length(1.4))
nf = d.add(elm.Dot())
d.add(elm.Line().right().tox(opB.out[0]-2.2))
d.add(elm.Resistor().right().tox(opB.out[0]).label('Rf 12k', loc='bottom'))
d.add(elm.Line().up().toy(opB.out[1]))
d.add(elm.Dot().at(opB.out))
d.add(elm.ResistorVar().down().at(nf.center).label('FSR 30 mm\n(J1 Pin 3 / 2)', loc='bottom'))
d.add(elm.Ground())
# ---- Sallen-Key U1A ----
d.add(elm.Label().at(opB.out).label('OUT B', loc='bottom', ofst=(0.5,-0.25)))
r1 = d.add(elm.Resistor().right().at(opB.out).label('R1\n100k'))
x = d.add(elm.Dot())
r2 = d.add(elm.Resistor().right().label('R2\n100k'))
n3 = d.add(elm.Dot())
c2 = d.add(elm.Capacitor().down().at(n3.center).label('C2\n47n X7R', loc='bottom'))
d.add(elm.Ground())
opA = d.add(elm.Opamp(leads=True).right().anchor('in2').at((n3.center[0]+1.5, n3.center[1])).label('U1A\nMCP602', loc='center', ofst=(0.2,0)))
d.add(elm.Line().at(n3.center).to(opA.in2))
d.add(elm.Label().at(opA.in2).label('3', loc='bottom', ofst=(-0.3,0)))
d.add(elm.Label().at(opA.in1).label('2', loc='top', ofst=(-0.3,0)))
d.add(elm.Label().at(opA.out).label('1', loc='top', ofst=(0.2,0)))
# follower: pin2 to out
d.add(elm.Line().up().at(opA.in1).length(1.0))
d.add(elm.Line().right().tox(opA.out[0]+0.6))
d.add(elm.Line().down().toy(opA.out[1]))
d.add(elm.Line().left().tox(opA.out[0]))
outA = (opA.out[0]+0.6, opA.out[1])
# C1 from X to OUT A (above)
d.add(elm.Line().up().at(x.center).length(3.0))
c1 = d.add(elm.Capacitor().right().tox(outA[0]+1.2).label('C1 100n X7R'))
d.add(elm.Line().down().toy(outA[1]))
d.add(elm.Dot())
d.add(elm.Line().left().tox(outA[0]))
d.add(elm.Line().right().at((outA[0]+1.2, outA[1])).length(1.0))
d.add(elm.Dot(open=True).label('A0 (XIAO D0)', loc='right'))
d.add(elm.Label().at((outA[0]+1.0, outA[1]-0.9)).label('≈ 23 Hz, Q ≈ 0,73', loc='right'))

# ---- Supply block ----
sx, sy = opA.out[0]+6.5, 4
d.add(elm.Vdd().at((sx, sy)).label('VDD (XIAO D1)'))
d.add(elm.Line().down().at((sx, sy)).length(0.8)); d.add(elm.Dot())
d.add(elm.Line().right().length(1.6))
d.add(elm.Capacitor().down().label('C3\n100n', loc='bottom')); d.add(elm.Ground())
d.add(elm.Line().down().at((sx, sy-0.8)).length(0.6))
d.add(elm.Label().label('U1 Pin 8', loc='left'))
d.add(elm.Line().down().at((sx, sy-3.4)).length(0.6))
d.add(elm.Label().at((sx, sy-3.4)).label('U1 Pin 4', loc='left'))
d.add(elm.Ground().at((sx, sy-4.0)))

# ---- Battery switch via J1 ----
bx, by = sx-0.4, -1.6
j = d.add(elm.Header(rows=4, pinsright=['1 LiPo+', '2 GND / FSR', '3 FSR / −IN B', '4 → BAT+'], pinalignright='center').at((bx, by)).anchor('pin1').label('J1 JST-XH', loc='top'))
d.add(elm.Label().at((opA.out[0]-6, -5.6)).label('Im FSR-Stecker: 1–4 gebrückt (Einschalter), 2–3 = FSR', loc='right'))
d.add(elm.Label().at((opA.out[0]-6, -6.3)).label('LiPo− → GND (XH-2), am XIAO ist BAT− = GND', loc='right'))
import sys; d.save(sys.argv[1] if len(sys.argv)>1 else 'schematic.svg')
